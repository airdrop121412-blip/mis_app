    /**
     * Import one child sheet into its DB table.
     *
     * @param  array<int, array<int, string|int|float|bool|null>>  $rows
     * @param  array{hh: array<string, int>, nid: array<string, int>}  $epIndex
     * @param  array<string, mixed>  $state  mutable cross-sheet state
     * @return array<string, mixed>
     */
    private function importChildSheet(string $key, array $rows, array $epIndex, array &$state): array
    {
        $report = [
            'sheet' => $key,
            'name' => self::SHEET_NAMES[$key] ?? $key,
            'total' => 0,
            'imported' => 0,
            'skipped' => 0,
            'missing_columns' => [],
            'unknown_columns' => [],
            'errors' => [],
        ];

        if ($rows === []) {
            return $report;
        }

        $fields = self::fieldsForSheet($key);
        $rules = self::CHILD_RULES[$key];

        $colMap = [];
        $unknownColumns = [];
        foreach ($rows[0] as $colIndex => $headerValue) {
            $code = self::headerField((string) ($headerValue ?? ''));
            if (isset($fields[$code])) {
                $colMap[$colIndex] = $code;
            } elseif (trim((string) $headerValue) !== '') {
                $unknownColumns[] = trim((string) $headerValue);
            }
        }

        $report['missing_columns'] = array_values(array_diff(
            self::REQUIRED_BY_SHEET[$key],
            array_values($colMap),
        ));
        $report['unknown_columns'] = array_values(array_unique($unknownColumns));

        foreach (array_slice($rows, 1) as $rowIndex => $row) {
            $excelRow = $rowIndex + 2;

            $raw = [];
            foreach ($colMap as $colIndex => $field) {
                if (array_key_exists($colIndex, $row)) {
                    $raw[$field] = $row[$colIndex];
                }
            }

            if (self::isEmptyRow($raw)) {
                continue;
            }
            $report['total']++;

            $data = self::normalizeRow($fields, $raw);

            [$data, $masterErrors] = $this->resolveMasterTexts($data);
            if ($masterErrors !== []) {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => $key,
                    'name' => (string) ($data['name'] ?? ''),
                    'errors' => $masterErrors,
                ];

                continue;
            }

            $hhId = trim((string) ($data['hh_id'] ?? ''));
            $nid = trim((string) ($data['nid_number'] ?? $data['ep_nid'] ?? ''));
            if ($hhId === '' && $nid === '') {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => $key,
                    'name' => (string) ($data['name'] ?? ''),
                    'errors' => ['hh_id' => ['Provide HH ID or the parent EP NID.']],
                ];

                continue;
            }
            $affectedPersonId = $hhId !== ''
                ? ($epIndex['hh'][$hhId] ?? null)
                : ($epIndex['nid'][$nid] ?? null);
            $parentKey = $hhId !== '' ? 'hh:'.$hhId : 'nid:'.$nid;
            if ($hhId !== '' && $nid !== ''
                && isset($epIndex['hh'][$hhId], $epIndex['nid'][$nid])
                && $epIndex['hh'][$hhId] !== $epIndex['nid'][$nid]) {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => $key,
                    'name' => (string) ($data['name'] ?? ''),
                    'errors' => ['hh_id' => [
                        'HH ID and parent EP NID refer to different EP records. Correct one value before uploading.',
                    ]],
                ];

                continue;
            }
            if ($affectedPersonId === null) {
                $linkColumn = $hhId !== '' ? 'hh_id' : ($key === 'tenant' ? 'ep_nid' : 'nid_number');
                $linkValue = $hhId !== '' ? $hhId : $nid;
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => $key,
                    'name' => (string) ($data['name'] ?? $nid),
                    'errors' => [$linkColumn => [
                        "No DRAFT EP found with {$linkColumn} '{$linkValue}' in this project. Import the EP row in the same workbook first.",
                    ]],
                ];

                continue;
            }

            $linkError = $this->resolveChildLinks($key, $data, $parentKey, $state);
            if ($linkError !== null) {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => $key,
                    'name' => (string) ($data['name'] ?? $nid),
                    'errors' => $linkError,
                ];

                continue;
            }

            // The worker's own NID arrives in «worker_nid» because «nid_number» is the
            // EP-link column on the worker sheet. Capture it before the link columns unset.
            $workerOwnNid = $key === 'worker' ? ($data['worker_nid'] ?? null) : null;

            // «nid_number» is the EP-link column on every child sheet except «ভাড়াটিয়া»
            // (tenant), where it holds the tenant's own NID and «ep_nid» is the link.
            unset($data['hh_id'], $data['ep_nid'], $data['land_no'], $data['tenant_no'], $data['structure_no'], $data['business_no'], $data['worker_nid']);
            if ($key !== 'tenant') {
                unset($data['nid_number']);
            }
            if ($workerOwnNid !== null) {
                $data['nid_number'] = $workerOwnNid;
            }

            $validator = Validator::make($data, $rules);
            if ($validator->fails()) {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => $key,
                    'name' => (string) ($data['name'] ?? $nid),
                    'errors' => $validator->errors()->messages(),
                ];

                continue;
            }

            try {
                $model = $this->createChild($key, $data, $affectedPersonId);
                $report['imported']++;
                $this->recordChildIds($key, $model, $parentKey, $state);
            } catch (\Throwable $e) {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => $key,
                    'name' => (string) ($data['name'] ?? $nid),
                    'errors' => ['exception' => [$e->getMessage()]],
                ];
            }
        }

        $report['skipped'] = count($report['errors']);

        return $report;
    }

    /**
     * Resolve intra-EP links (crop → land, business → tenant) and mutate
     * $data in place. Returns an errors array, or null on success.
     *
     * @param  array<string, mixed>  $data
     * @param  array<string, mixed>  $state
     * @return array<string, array<int, string>>|null
     */
    private function resolveChildLinks(string $key, array &$data, string $parentKey, array &$state): ?array
    {
        if ($key === 'crop') {
            $landNo = (int) ($data['land_no'] ?? 0);
            $landId = $state['land_ids_by_parent'][$parentKey][$landNo - 1] ?? null;

            if ($landNo < 1 || $landId === null) {
                return ['land_no' => [
                    "Land #{$landNo} not found for this EP. Import the lands in the same upload and number them by their row order in the «আবাদি জমি» sheet.",
                ]];
            }

            $data['land_id'] = $landId;

            return null;
        }

        if ($key === 'tenant') {
            $structureNo = (int) ($data['structure_no'] ?? 0);
            if ($structureNo >= 1) {
                $structureId = $state['structure_ids_by_parent'][$parentKey][$structureNo - 1] ?? null;

                if ($structureId === null) {
                    return ['structure_no' => [
                        "Structure #{$structureNo} not found for this EP. Import the structures in the same upload and number them by their row order in the «কাঠামো» sheet.",
                    ]];
                }

                $data['infrastructure_id'] = $structureId;
            }

            return null;
        }

        if ($key === 'business') {
            if (strtoupper((string) ($data['ownership_code'] ?? '')) === 'TENANT') {
                $tenantNo = (int) ($data['tenant_no'] ?? 0);
                $tenantId = $state['tenant_ids_by_parent'][$parentKey][$tenantNo - 1] ?? null;

                if ($tenantId === null) {
                    return ['tenant_no' => [
                        "TENANT businesses must reference a tenant imported for this EP. Fill «ভাড়াটিয়া ক্রমিক নং» with the tenant's row order in the «ভাড়াটিয়া» sheet.",
                    ]];
                }

                $data['tenant_id'] = $tenantId;
            } else {
                $data['tenant_id'] = null;
            }

            return null;
        }

        if ($key === 'worker' && ($data['business_no'] ?? null) !== null && (string) $data['business_no'] !== '') {
            $businessNo = (int) $data['business_no'];
            $businessId = $state['business_ids_by_parent'][$parentKey][$businessNo - 1] ?? null;

            if ($businessId === null) {
                return ['business_no' => [
                    "Business #{$businessNo} not found for this EP. Import the businesses in the same upload and number them by their row order in the «ব্যবসা» sheet.",
                ]];
            }

            $data['business_id'] = $businessId;
        }

        return null;
    }

    /**
     * @param  array<string, mixed>  $data
     *
     * @throws BusinessRuleException when an indirect EP ID
     *                               cannot be generated (missing code / collision)
     */
    private function createChild(string $key, array $data, int $affectedPersonId): object
    {
        $data['affected_person_id'] = $affectedPersonId;

        if ($key === 'land') {
            // Auto-derive land_status_id from the parent EP when left blank
            // in the land sheet (mirrors the LandController behaviour).
            if (empty($data['land_status_id'])) {
                $ep = $this->epCache[$affectedPersonId] ??= AffectedPerson::find($affectedPersonId);
                if ($ep && $ep->land_status_id) {
                    $data['land_status_id'] = $ep->land_status_id;
                }
            }
        }

        if ($key === 'tenant' || $key === 'worker') {
            $ep = $this->epCache[$affectedPersonId] ??= AffectedPerson::findOrFail($affectedPersonId);

            if ($key === 'tenant') {
                $data['hh_id'] = $ep->hh_id;
                $data['district_id'] = $data['district_id'] ?? $ep->district_id;
                $data['upazila_id'] = $data['upazila_id'] ?? $ep->upazila_id;
            }

            $data['ep_id'] = $this->epIdService->generateIndirect(
                $ep->project_id,
                $ep->district_id,
                $ep->upazila_id,
                $ep->land_status_id,
                $key === 'tenant' ? 'Tenant' : 'Wage Loss',
                $key === 'tenant' ? 'EP_SERIAL_TENANT' : 'EP_SERIAL_WORKER',
                $ep->ownership,
                $ep->phase,
            );
        }

        return match ($key) {
            'family' => FamilyMember::create($data),
            'land' => Land::create($data),
            'crop' => Crop::create($data),
            'structure' => Infrastructure::create($data),
            'tree' => Tree::create($data),
            'tenant' => Tenant::create($data),
            'business' => Business::create($data),
            'worker' => Worker::create($data),
        };
    }

    /**
     * Collect created ids so crop → land and business → tenant links resolve.
     *
     * @param  array<string, mixed>  $state
     */
    private function recordChildIds(string $key, object $model, string $parentKey, array &$state): void
    {
        if ($key === 'land') {
            $state['land_ids_by_parent'][$parentKey][] = $model->land_id;
        }

        if ($key === 'tenant') {
            $state['tenant_ids_by_parent'][$parentKey][] = $model->tenant_id;
        }

        if ($key === 'business') {
            $state['business_ids_by_parent'][$parentKey][] = $model->business_id;
        }

        if ($key === 'structure') {
            $state['structure_ids_by_parent'][$parentKey][] = $model->infrastructure_id;
        }
    }

