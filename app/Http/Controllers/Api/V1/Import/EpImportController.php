    private static function uploadError(): int
    {
        return (int) ($_FILES['file']['error'] ?? UPLOAD_ERR_NO_FILE);
    }

    /**
     * Turn a PHP upload error code into an actionable sentence.
     */
    private static function uploadErrorMessage(int $code): string
    {
        return match ($code) {
            UPLOAD_ERR_INI_SIZE, UPLOAD_ERR_FORM_SIZE => sprintf(
                'That workbook is too large — the server accepts up to %s per upload. '
                .'Delete unused sheets or split the data across two uploads, then retry.',
                ini_get('upload_max_filesize') ?: '2M',
            ),
            UPLOAD_ERR_PARTIAL => 'The file was only partially received. Check your connection and upload again.',
            UPLOAD_ERR_NO_TMP_DIR => 'The server has no temporary folder available for uploads — contact the administrator.',
            UPLOAD_ERR_CANT_WRITE => 'The server could not write the uploaded file to disk — contact the administrator.',
            UPLOAD_ERR_EXTENSION => 'A PHP extension blocked the upload — contact the administrator.',
            default => 'The file failed to upload. Please try again.',
        };
    }

    public function import(Request $request): JsonResponse
    {
        // When a file exceeds upload_max_filesize / post_max_size PHP discards it
        // before Laravel runs, so the validator can only say "failed to upload".
        // Detect that case up front and explain it properly.
        if ($request->hasFile('file') === false && self::uploadError() !== UPLOAD_ERR_NO_FILE) {
            return ApiResponse::error(
                self::uploadErrorMessage(self::uploadError()),
                'IMPORT_FILE_REJECTED',
                422,
                ['file' => [self::uploadErrorMessage(self::uploadError())]],
            );
        }

        $maxKb = (int) ((int) (ini_get('upload_max_filesize') ?: '2M') * 1024);

        $validator = Validator::make($request->all(), [
            'project_id' => ['required', 'integer', 'exists:project,project_id'],
            'file' => ['required', 'file', 'mimes:xlsx', "max:{$maxKb}"],
        ], [
            'project_id.required' => 'Select a project before importing.',
            'project_id.exists' => 'The selected project no longer exists — reload the page and pick another.',
            'file.required' => 'No file was received. Choose your filled .xlsx workbook and try again.',
            'file.file' => 'The uploaded value is not a file. Use the .xlsx workbook downloaded from this page.',
            'file.mimes' => 'Only .xlsx workbooks are accepted. If your file is .xls, .csv or .xlsb, open it in Excel and Save As "Excel Workbook (.xlsx)".',
            'file.max' => 'That workbook is larger than the '.ini_get('upload_max_filesize').' upload limit. Remove empty formatting/extra sheets, or split the data into two uploads.',
        ]);

        if ($validator->fails()) {
            $bag = $validator->errors()->toArray();
            $first = (string) collect($bag)->flatten()->first();

            return ApiResponse::error(
                $first !== '' ? $first : 'The upload could not be validated.',
                'IMPORT_VALIDATION_FAILED',
                422,
                $bag,
            );
        }

        $projectId = (int) $request->input('project_id');
        $file = $request->file('file');

        try {
            $sheets = XlsxReader::readSheets($file->getRealPath());
        } catch (\InvalidArgumentException $e) {
            return ApiResponse::error($e->getMessage(), 'INVALID_XLSX');
        }
        $epName = self::SHEET_NAMES['ep'];
        $epRows = $sheets[$epName] ?? null;
        if ($epRows === null) {
            return ApiResponse::error(
                'The workbook must contain the «'.$epName.'» sheet (the template\'s first sheet).',
                'EP_SHEET_MISSING',
            );
        }

        // Large workbooks (15 000+ rows) can legitimately take many minutes
        // to import. Remove PHP's execution-time and memory limits so the
        // import runs to completion instead of being killed at the 300 s mark.
        set_time_limit(0);
        ini_set('max_execution_time', 0);
        ini_set('memory_limit', '-1');

        // 1) Import the EP sheet first (unchanged behaviour).
        $epReport = $this->importEpSheet($epRows, $projectId);

        // 2) Index every DRAFT EP by HH ID and NID so child sheets can link
        //    to both newly-imported and already-existing EPs.
        $epIndex = $this->epIndexByParentKeys($projectId);

        // 3) Import each child sheet.
        $state = ['land_ids_by_parent' => [], 'tenant_ids_by_parent' => [], 'structure_ids_by_parent' => [], 'business_ids_by_parent' => []];
        $reports = ['ep' => $epReport];

        foreach (self::CHILD_KEYS as $key) {
            $rows = $sheets[self::SHEET_NAMES[$key]] ?? [];
            $reports[$key] = $this->importChildSheet($key, $rows, $epIndex, $state);
        }

        // 4) Import GPS sheet (updates EP records in place).
        $gpsRows = $sheets[self::SHEET_NAMES['gps']] ?? [];
        if ($gpsRows !== []) {
            $reports['gps'] = $this->importGpsSheet($gpsRows, $epIndex);
        }

        $allErrors = [];
        $total = 0;
        $imported = 0;
        foreach ($reports as $report) {
            $total += $report['total'];
            $imported += $report['imported'];
            $allErrors = array_merge($allErrors, $report['errors']);
        }

        $skipped = count($allErrors);

        $message = $skipped > 0
            ? "Imported {$imported} of {$total} rows; {$skipped} row(s) skipped."
            : "Imported {$imported} of {$total} rows.";

        return ApiResponse::success([
            'total' => $total,
            'imported' => $imported,
            'skipped' => $skipped,
            'imported_ids' => $epReport['imported_ids'],
            'missing_columns' => $epReport['missing_columns'],
            'unknown_columns' => $epReport['unknown_columns'],
            'errors' => $allErrors,
            'sheets' => $reports,
                ], $message);
    }

    // ── Step-by-step import (single sheet per request) ──────────────────

    /**
     * POST /api/v1/imports/ep/step — import a single sheet.
     *
     * Allows step-by-step upload: the user uploads one data sheet at a time
     * (EP → Family → Land → Crop → Structure → Tree → Tenant → Business →
     * Worker → GPS). Each step validates + inserts rows for just that sheet,
     * linking to EPs already drafted in the project.
     */
    public function importStep(Request $request): JsonResponse
    {
        $step = $request->input('step');

        $validator = Validator::make($request->all(), [
            'project_id' => ['required', 'integer', 'exists:project,project_id'],
            'step'       => ['required', 'string', function ($attribute, $value, $fail): void {
                $validSteps = array_keys(self::SHEET_NAMES);
                if (! in_array($value, $validSteps, true)) {
                    $fail("Invalid step '{$value}'. Must be one of: " . implode(', ', $validSteps));
                }
            }],
            'file'       => ['required', 'file', 'mimes:xlsx'],
            'upload_key' => ['nullable', 'string'],
            'offset'     => ['nullable', 'integer', 'min:0'],
            'batch_size' => ['nullable', 'integer', 'min:1', 'max:500'],
        ], [
            'project_id.required' => 'Select a project before importing.',
            'project_id.exists'   => 'The selected project no longer exists — reload and pick another.',
            'file.required'       => 'No file was received. Choose your filled .xlsx file and try again.',
            'file.file'           => 'The uploaded file is not valid.',
            'file.mimes'          => 'Only .xlsx files are supported (.xls is not).',
        ]);

        if ($validator->fails()) {
            return ApiResponse::error(
                'Validation failed.',
                'VALIDATION_ERROR',
                422,
                $validator->errors()->toArray(),
            );
        }

        // Large workbooks (15 000+ rows) can legitimately take many minutes
        // to import. Remove PHP's execution-time and memory limits so the
        // import runs to completion instead of being killed at the 300 s mark.
        set_time_limit(0);
        ini_set('max_execution_time', 0);
        ini_set('memory_limit', '-1');

        $projectId = (int) $request->input('project_id');
        $file = $request->file('file');
        $sheetName = self::SHEET_NAMES[$step];

        // ── Chunked (continuation) import ─────────────────────────────
        // One HTTP request = one batch. Parsed rows are cached server-side
        // under upload_key so we never re-parse the file on subsequent
        // batch requests. Every request stays well under the platform
        // request timeout — no single request ever approaches the limit.
        $uploadKey = $request->input('upload_key');
        $offset    = (int) $request->input('offset', 0);
        $batchSize = (int) $request->input('batch_size', 50);

        if ($uploadKey === null) {
            try {
                $rows = XlsxReader::readSheet($file->getRealPath(), $sheetName);
            } catch (\InvalidArgumentException $e) {
                return ApiResponse::error($e->getMessage(), 'INVALID_XLSX');
            }
            if (empty($rows)) {
                return ApiResponse::error(
                    "No data found in the «{$sheetName}» sheet. Ensure the first row has the field headers and the sheet is not empty.",
                    'SHEET_EMPTY',
                );
            }
            $uploadKey = (string) Str::uuid();
            Cache::put("import_rows:{$uploadKey}", $rows, now()->addMinutes(30));
        } else {
            $rows = Cache::get("import_rows:{$uploadKey}");
            if ($rows === null) {
                return ApiResponse::error(
                    'Upload session expired. Please re-upload the file.',
                    'UPLOAD_SESSION_EXPIRED',
                    410,
                );
            }
        }

        $totalDataRows = count($rows) - 1; // minus header row
        if ($totalDataRows <= 0) {
            return ApiResponse::error(
                "No data found in the «{$sheetName}» sheet. Ensure the first row has the field headers and the sheet is not empty.",
                'SHEET_EMPTY',
            );
        }

        // Slice one batch of data rows (skip header at index 0).
        $dataRows = array_slice($rows, 1);
        $batchData = array_slice($dataRows, $offset, $batchSize);
        $batchRows = array_merge([$rows[0]], $batchData);

        $done = ($offset + $batchSize) >= $totalDataRows;
        $nextOffset = $done ? null : $offset + $batchSize;

        $epIndex = null;
        $state   = null;

        if ($step === 'ep') {
            $report = $this->importEpSheet($batchRows, $projectId);
        } elseif ($step === 'gps') {
            $epIndex = $this->epIndexByParentKeys($projectId);
            $report = $this->importGpsSheet($batchRows, $epIndex);
        } else {
            $epIndex = $this->epIndexByParentKeys($projectId);
            $state   = $this->buildStateFromDb($projectId);
            $report = $this->importChildSheet($step, $batchRows, $epIndex, $state);
        }

        $report['skipped'] = count($report['errors']);

        $message = sprintf(
            'Imported %d of %d rows (offset %d%s).',
            $report['imported'],
            $totalDataRows,
            $offset,
            $done ? ' — complete' : ', more batches remain'
        );

        return ApiResponse::success([
            'step'               => $step,
            'sheet_name'         => self::SHEET_NAMES[$step],
            'upload_key'         => $uploadKey,
            'total_rows'         => $totalDataRows,
            'imported'           => $report['imported'],
            'skipped'            => $report['skipped'],
            'offset'             => $offset,
            'next_offset'        => $nextOffset,
            'batch_size'         => $batchSize,
            'done'               => $done,
            'missing_columns'    => $report['missing_columns'],
            'unknown_columns'    => $report['unknown_columns'],
            'errors'             => $report['errors'],
            'imported_ids'       => $report['imported_ids'] ?? [],
        ], $message);
    }

