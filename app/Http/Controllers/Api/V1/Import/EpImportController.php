    /**
     * @param  array<string, mixed>  $raw
     * @return array<string, mixed>
     */
    private static function normalizeRow(array $fields, array $raw): array
    {
        $data = [];

        foreach ($fields as $field => [$_, $__, $type]) {
            if (! array_key_exists($field, $raw)) {
                continue;
            }

            $value = $raw[$field];
            if (is_string($value)) {
                $value = trim(str_replace("\u{00A0}", ' ', $value));
                if ($value === '') {
                    $value = null;
                }
            }

            if ($value === null) {
                continue;
            }

            $data[$field] = match ($type) {
                'boolean' => self::toBool($value),
                // Master-data columns keep their raw value so resolveMasterTexts()
                // can turn text like "Male" into the matching master ID.
                'number' => isset(self::MASTER_COLUMNS[$field]) ? $value : self::toNumber($value),
                'date' => self::toDate($value),
                default => is_scalar($value) ? (string) $value : (string) $value,
            };
        }

        return $data;
    }

    /**
     * Resolve master-data columns that contain plain TEXT (e.g. "Male") into
     * their IDs. Unmatched text falls back to the master's "Other" row, and
     * the original text is copied into the column's "*_other" specify field
     * (when the record has one). Numeric values pass through untouched, so
     * old ID-based templates keep working. Fixed-list text columns (e.g.
     * structure_material) are canonicalised the same way.
     *
     * @param  array<string, mixed>  $data
     * @return array{0: array<string, mixed>, 1: array<string, array<int, string>>}
     *                                                                              [mutated data, field-level errors for values that matched nothing]
     */
    private function resolveMasterTexts(array $data): array
    {
        $errors = [];

        foreach (self::MASTER_COLUMNS as $field => [$table, $otherField]) {
            if (! array_key_exists($field, $data) || $data[$field] === null || is_bool($data[$field])) {
                continue;
            }

            $value = $data[$field];

            // Numeric IDs are still accepted exactly as before.
            if (is_int($value) || (is_float($value) && floor($value) === $value)) {
                $data[$field] = (int) $value;

                continue;
            }

            $text = trim((string) $value);
            if ($text === '') {
                unset($data[$field]);

                continue;
            }

            if (preg_match('/^\d+$/', $text)) {
                $data[$field] = (int) $text;

                continue;
            }

            // Upazila names repeat across districts (and village names across
            // upazilas) — prefer the row's own district/upazila when known.
            $parentId = null;
            if ($table === 'upazila' && isset($data['district_id']) && is_numeric($data['district_id'])) {
                $parentId = (int) $data['district_id'];
            } elseif ($table === 'village' && isset($data['upazila_id']) && is_numeric($data['upazila_id'])) {
                $parentId = (int) $data['upazila_id'];
            }

            $lookup = $this->masterLookup($table);
            $id = self::findMasterId($lookup, $text, $parentId);

            if ($id === null) {
                if ($lookup['other_id'] !== null) {
                    $id = $lookup['other_id'];
                    if ($otherField !== null && trim((string) ($data[$otherField] ?? '')) === '') {
                        $data[$otherField] = $text;
                    }
                } else {
                    $errors[$field] = [
                        "'{$text}' did not match any {$table} entry. Use one of: "
                        .implode(', ', array_slice($lookup['names'], 0, 20)),
                    ];

                    continue;
                }
            }

            $data[$field] = $id;
        }

        foreach (self::TEXT_ENUM_COLUMNS as $field => [$allowed, $otherField]) {
            if (! array_key_exists($field, $data) || ! is_string($data[$field])) {
                continue;
            }

            $text = trim($data[$field]);
            foreach ($allowed as $canonical) {
                if (strcasecmp($canonical, $text) === 0) {
                    $data[$field] = $canonical;

                    continue 2;
                }
            }

            if ($otherField !== null) {
                $data[$field] = 'Other';
                if (trim((string) ($data[$otherField] ?? '')) === '') {
                    $data[$otherField] = $text;
                }
            }
        }

        return [$data, $errors];
    }

    /**
     * Build (and cache) the text → ID lookup for one master table.
     *
     * @return array{entries: array<int, array{id: int, key: string, parent_id: int|null}>, other_id: int|null, names: array<int, string>}
     */
    private function masterLookup(string $table): array
    {
        if (isset($this->masterLookups[$table])) {
            return $this->masterLookups[$table];
        }

        $pk = $table === 'residential_commercial_type' ? 'rc_type_id' : $table.'_id';
        $parentColumn = match ($table) {
            'upazila' => 'district_id',
            'village' => 'upazila_id',
            default => null,
        };

        // Not every master table carries a `code` column — `village` does not.
        // Selecting it unconditionally makes the whole lookup blow up with
        // "Unknown column 'code' in 'field list'" and fails the entire import.
        $columns = [$pk.' as id', 'name'];
        if (Schema::hasColumn($table, 'code')) {
            $columns[] = 'code';
        }
        if ($parentColumn !== null) {
            $columns[] = $parentColumn;
        }

        $lookup = ['entries' => [], 'other_id' => null, 'names' => []];

        foreach (DB::table($table)->where('is_active', 1)->get($columns) as $row) {
            $id = (int) $row->id;
            $parentId = $parentColumn !== null ? (int) $row->{$parentColumn} : null;
            $code = (string) ($row->code ?? '');

            foreach (array_unique([(string) ($row->name ?? ''), $code]) as $label) {
                $key = self::masterKey($label);
                if ($key !== '') {
                    $lookup['entries'][] = ['id' => $id, 'key' => $key, 'parent_id' => $parentId];
                }
            }

            if ($row->name !== null && ! in_array($row->name, $lookup['names'], true)) {
                $lookup['names'][] = (string) $row->name;
            }

            if ($lookup['other_id'] === null
                && (strcasecmp($code, 'OTHER') === 0 || strcasecmp((string) $row->name, 'Other') === 0)) {
                $lookup['other_id'] = $id;
            }
        }

        return $this->masterLookups[$table] = $lookup;
    }

    /**
     * Find the master ID for a free-text value; when several entries share a
     * name (e.g. upazilas in different districts) the parent ID breaks the tie.
     *
     * @param  array{entries: array<int, array{id: int, key: string, parent_id: int|null}>}  $lookup
     */
    private static function findMasterId(array $lookup, string $text, ?int $parentId): ?int
    {
        $key = self::masterKey($text);
        if ($key === '') {
            return null;
        }

        $matches = [];
        foreach ($lookup['entries'] as $entry) {
            if ($entry['key'] === $key) {
                $matches[] = $entry;
            }
        }

        if ($matches === []) {
            return null;
        }

        if ($parentId !== null && count($matches) > 1) {
            foreach ($matches as $entry) {
                if ($entry['parent_id'] === $parentId) {
                    return $entry['id'];
                }
            }
        }

        return $matches[0]['id'];
    }

    /**
     * Normalise a text value for case-insensitive master matching.
     */
    private static function masterKey(string $value): string
    {
        $value = html_entity_decode($value);
        $value = preg_replace('/\s+/u', ' ', $value) ?? $value;

        return mb_strtolower(trim($value));
    }

    private static function toBool(mixed $value): bool
    {
        $norm = html_entity_decode((string) $value);
        $norm = strtolower(trim($norm));

        return in_array($norm, ['1', 'true', 'yes', 'y', 'হ্যাঁ', 'হ্য'], true);
    }

    private static function toNumber(mixed $value): int|float
    {
        $raw = (string) $value;
        $raw = str_replace([',', ' ', '৳', 'টাকা'], '', $raw);

        if (preg_match('/^-?\d+$/', $raw)) {
            return (int) $raw;
        }

        return (float) $raw;
    }

    private static function toDate(mixed $value): ?string
    {
        $raw = trim((string) $value);

        // Excel date serial number (days since 1899-12-30, Lotus 1900 bug).
        if (preg_match('/^\d+(?:\.\d+)?$/', $raw)) {
            $serial = (float) $raw;
            if ($serial >= 1 && $serial <= 80000) {
                $base = $serial < 60 ? '1899-12-31' : '1899-12-30';

                return date('Y-m-d', strtotime($base.' + '.(int) floor($serial).' days'));
            }
        }

        $raw = trim(preg_replace('/[T\s].*$/', '', $raw));

        foreach (['Y-m-d', 'd-m-Y', 'd/m/Y', 'd.m.Y', 'Y/m/d', 'm/d/Y'] as $format) {
            $parsed = \DateTime::createFromFormat($format, $raw);
            if ($parsed !== false) {
                $errors = \DateTime::getLastErrors();
                if ($errors === false || ($errors['warning_count'] === 0 && $errors['error_count'] === 0)) {
                    return $parsed->format('Y-m-d');
                }
            }
        }

        return null;
    }

    /**
     * @param  array<string, mixed>  $raw
     */
    private static function isEmptyRow(array $raw): bool
    {
        foreach ($raw as $value) {
            if (is_scalar($value) && trim((string) $value) !== '') {
                return false;
            }
        }

        return true;
    }

    /**
     * Extract the field code from a header cell like "name | নাম".
     */
    private static function headerField(string $header): string
    {
        if (str_contains($header, '|')) {
            $code = trim(explode('|', $header, 2)[0]);
        } else {
            $code = trim($header);
        }

        return strtolower($code);
    }

    /**
     * Index every DRAFT EP of the project by its (trimmed) HH ID and NID.
     *
     * @return array<string, int>
     */
    private function epIndexByParentKeys(int $projectId): array
    {
        $eps = AffectedPerson::where('project_id', $projectId)
            ->where('status', 'DRAFT')
            ->get(['affected_person_id', 'hh_id', 'nid_number']);

        $index = ['hh' => [], 'nid' => []];
        foreach ($eps as $ep) {
            $hhId = trim((string) ($ep->hh_id ?? ''));
            $nid = trim((string) ($ep->nid_number ?? ''));
            if ($hhId !== '') {
                $index['hh'][$hhId] = $ep->affected_person_id;
            }
            if ($nid !== '') {
                $index['nid'][$nid] = $ep->affected_person_id;
            }
        }

        return $index;
    }

    /**
     * Rebuild the cross-sheet state array from the database.
     *
     * For step-by-step imports, child sheets reference parents (land,
     * structure, tenant, business) imported in earlier steps. This method
     * queries those tables and groups IDs by parent key (hh:XX or nid:YY),
     * ordered by insertion so row-order references resolve correctly.
     *
     * @return array{land_ids_by_parent: array<string, array<int, int>>, tenant_ids_by_parent: array<string, array<int, int>>, structure_ids_by_parent: array<string, array<int, int>>, business_ids_by_parent: array<string, array<int, int>>}
     */
    private function buildStateFromDb(int $projectId): array
    {
        $state = [
            'land_ids_by_parent'       => [],
            'tenant_ids_by_parent'     => [],
            'structure_ids_by_parent'  => [],
            'business_ids_by_parent'   => [],
        ];

        // Map affected_person_id → parentKey (hh:XX or nid:YY) from DRAFT EPs.
        $epParentKeys = AffectedPerson::where('project_id', $projectId)
            ->where('status', 'DRAFT')
            ->get(['affected_person_id', 'hh_id', 'nid_number'])
            ->mapWithKeys(function ($ep) {
                $hhId = trim((string) ($ep->hh_id ?? ''));
                $nid  = trim((string) ($ep->nid_number ?? ''));
                $key  = $hhId !== '' ? 'hh:'.$hhId : ($nid !== '' ? 'nid:'.$nid : null);

                return [$ep->affected_person_id => $key];
            })
            ->filter()
            ->toArray();

        // Lands
        $lands = DB::table('land')
            ->join('affected_person', 'land.affected_person_id', '=', 'affected_person.affected_person_id')
            ->where('affected_person.project_id', $projectId)
            ->orderBy('land.land_id')
            ->get(['land.land_id', 'land.affected_person_id']);
        foreach ($lands as $land) {
            $pk = $epParentKeys[$land->affected_person_id] ?? null;
            if ($pk !== null) {
                $state['land_ids_by_parent'][$pk][] = $land->land_id;
            }
        }

        // Structures (infrastructures)
        $structures = DB::table('infrastructure')
            ->join('affected_person', 'infrastructure.affected_person_id', '=', 'affected_person.affected_person_id')
            ->where('affected_person.project_id', $projectId)
            ->orderBy('infrastructure.infrastructure_id')
            ->get(['infrastructure.infrastructure_id', 'infrastructure.affected_person_id']);
        foreach ($structures as $struct) {
            $pk = $epParentKeys[$struct->affected_person_id] ?? null;
            if ($pk !== null) {
                $state['structure_ids_by_parent'][$pk][] = $struct->infrastructure_id;
            }
        }

        // Tenants
        $tenants = DB::table('tenant')
            ->join('affected_person', 'tenant.affected_person_id', '=', 'affected_person.affected_person_id')
            ->where('affected_person.project_id', $projectId)
            ->orderBy('tenant.tenant_id')
            ->get(['tenant.tenant_id', 'tenant.affected_person_id']);
        foreach ($tenants as $tenant) {
            $pk = $epParentKeys[$tenant->affected_person_id] ?? null;
            if ($pk !== null) {
                $state['tenant_ids_by_parent'][$pk][] = $tenant->tenant_id;
            }
        }

        // Businesses
        $businesses = DB::table('business')
            ->join('affected_person', 'business.affected_person_id', '=', 'affected_person.affected_person_id')
            ->where('affected_person.project_id', $projectId)
            ->orderBy('business.business_id')
            ->get(['business.business_id', 'business.affected_person_id']);
        foreach ($businesses as $business) {
            $pk = $epParentKeys[$business->affected_person_id] ?? null;
            if ($pk !== null) {
                $state['business_ids_by_parent'][$pk][] = $business->business_id;
            }
        }

        return $state;
    }

    /**
     * Import the «GPS তথ্য» sheet: update each linked EP's GPS coordinates in place.
     *
     * @param  array<int, array<int, string|int|float|bool|null>>  $rows
     * @return array<string, mixed>
     */
    private function importGpsSheet(array $rows, array $epIndex): array
    {
        $report = [
            'sheet' => 'gps',
            'name' => self::SHEET_NAMES['gps'],
            'total' => 0,
            'imported' => 0,
            'skipped' => 0,
            'missing_columns' => [],
            'unknown_columns' => [],
            'errors' => [],
        ];

        $colMap = [];
        $unknownColumns = [];
        foreach ($rows[0] as $colIndex => $headerValue) {
            $code = self::headerField((string) ($headerValue ?? ''));
            if (isset(self::GPS_FIELDS[$code])) {
                $colMap[$colIndex] = $code;
            } elseif (trim((string) $headerValue) !== '') {
                $unknownColumns[] = trim((string) $headerValue);
            }
        }

        $report['missing_columns'] = array_values(array_diff(
            ['hh_id', 'nid_number', 'gps_latitude', 'gps_longitude'],
            array_values($colMap),
        ));
        $report['unknown_columns'] = array_values($unknownColumns);

        foreach (array_slice($rows, 1) as $rowIndex => $row) {
            $excelRow = $rowIndex + 2;

            $raw = [];
            foreach ($colMap as $colIndex => $field) {
                if (array_key_exists($colIndex, $row)) {
                    $raw[$field] = $row[$colIndex];
                }
            }

            if (self::isEmptyRow($raw)) {
                continue;
            }
            $report['total']++;

            $data = self::normalizeRow(self::GPS_FIELDS, $raw);

            $hhId = trim((string) ($data['hh_id'] ?? ''));
            $nid = trim((string) ($data['nid_number'] ?? ''));
            if ($hhId === '' && $nid === '') {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => 'gps',
                    'name' => '',
                    'errors' => ['hh_id' => ['Provide HH ID or NID to link this GPS record to an EP.']],
                ];

                continue;
            }

            $affectedPersonId = $hhId !== ''
                ? ($epIndex['hh'][$hhId] ?? null)
                : ($epIndex['nid'][$nid] ?? null);

            if ($affectedPersonId === null) {
                $linkColumn = $hhId !== '' ? 'hh_id' : 'nid_number';
                $linkValue = $hhId !== '' ? $hhId : $nid;
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => 'gps',
                    'name' => '',
                    'errors' => [$linkColumn => [
                        "No DRAFT EP found with {$linkColumn} '{$linkValue}' in this project. Import the EP row in the same workbook first.",
                    ]],
                ];

                continue;
            }

            $latitude = $data['gps_latitude'] ?? null;
            $longitude = $data['gps_longitude'] ?? null;
            if ($latitude === null || $longitude === null) {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => 'gps',
                    'name' => '',
                    'errors' => ['gps_latitude' => ['Both GPS latitude and longitude are required.']],
                ];

                continue;
            }

            try {
                AffectedPerson::where('affected_person_id', $affectedPersonId)->update([
                    'gps_latitude' => $latitude,
                    'gps_longitude' => $longitude,
                ]);
                $report['imported']++;
            } catch (\Throwable $e) {
                $report['errors'][] = [
                    'row' => $excelRow,
                    'sheet' => 'gps',
                    'name' => '',
                    'errors' => ['exception' => [$e->getMessage()]],
                ];
            }
        }

                $report['skipped'] = count($report['errors']);

        return $report;
    }

    // ── Step-by-step clear (reset one table before re-upload) ──────

    /**
     * DELETE /api/v1/imports/ep/step/{step}
     *
     * Remove every DRAFT row belonging to the given import step (sheet) for
     * the requested project. Lets the operator reset one table after an error
     * or partial upload, then re-upload cleanly.
     *
     * Child tables are emptied in the correct FK order so no constraint errors
     * occur. Only DRAFT EPs and their descendants are touched.
     */
    public function clearStep(Request $request, string $step): JsonResponse
    {
        $validSteps = array_keys(self::SHEET_NAMES);
        if (!in_array($step, $validSteps, true)) {
            return ApiResponse::error(
                "Invalid step '{$step}'. Must be one of: " . implode(', ', $validSteps),
                'INVALID_STEP',
                422,
            );
        }

        $projectId = $request->input('project_id');
        if (!$projectId || !is_numeric($projectId)) {
            return ApiResponse::error('A project_id is required.', 'PROJECT_ID_REQUIRED', 422);
        }
        $projectId = (int) $projectId;

        set_time_limit(0);
        ini_set('max_execution_time', 0);
        ini_set('memory_limit', '-1');

        $deletedCount = DB::transaction(function () use ($step, $projectId): int {
            return $this->clearStepData($step, $projectId);
        });

        return ApiResponse::success(
            ['deleted' => $deletedCount, 'step' => $step],
            "Cleared {$deletedCount} {$step} record(s) for this project.",
        );
    }

    /**
     * GET /api/v1/imports/ep/step/{step}/count?project_id=X
     *
     * Return the number of DRAFT rows that belong to a given import step
     * for the requested project. Lets the UI show a badge in the sidebar
     * when data exists for a step (so the operator knows there is data
     * to clear before re-uploading).
     */
    public function countStepData(Request $request, string $step): JsonResponse
    {
        $validSteps = array_keys(self::SHEET_NAMES);
        if (!in_array($step, $validSteps, true)) {
            return ApiResponse::error(
                "Invalid step '{$step}'.",
                'INVALID_STEP',
                422,
            );
        }

        $projectId = $request->input('project_id');
        if (!$projectId || !is_numeric($projectId)) {
            return ApiResponse::error('A project_id is required.', 'PROJECT_ID_REQUIRED', 422);
        }
        $projectId = (int) $projectId;

        $count = $this->countStepRows($step, $projectId);

        return ApiResponse::success(
            ['count' => $count, 'step' => $step],
            "Found {$count} {$step} record(s).",
        );
    }

    /**
     * Count DRAFT rows for one import step using the same FK-scoped
     * subqueries as clearStepData().
     */
    private function countStepRows(string $step, int $projectId): int
    {
        $ap = fn () => DB::table('affected_person')
            ->where('project_id', $projectId)
            ->where('status', 'DRAFT')
            ->select('affected_person_id');

        $land = fn () => DB::table('land')
            ->whereIn('affected_person_id', $ap())
            ->select('land_id');

        $crop = fn () => DB::table('crop')
            ->whereIn('land_id', $land())
            ->select('crop_id');

        $infra = fn () => DB::table('infrastructure')
            ->whereIn('affected_person_id', $ap())
            ->select('infrastructure_id');

        $tree = fn () => DB::table('tree')
            ->whereIn('affected_person_id', $ap())
            ->select('tree_id');

        $tenant = fn () => DB::table('tenant')
            ->whereIn('affected_person_id', $ap())
            ->select('tenant_id');

        $biz = fn () => DB::table('business')
            ->whereIn('affected_person_id', $ap())
            ->select('business_id');

        $tenantBiz = fn () => DB::table('business')
            ->whereIn('tenant_id', $tenant())
            ->select('business_id');

        $worker = fn () => DB::table('worker')
            ->whereIn('affected_person_id', $ap())
            ->select('worker_id');

        switch ($step) {
            case 'ep':
                return DB::table('affected_person')
                    ->where('project_id', $projectId)
                    ->where('status', 'DRAFT')
                    ->count();
            case 'family':
                return DB::table('family_member')
                    ->whereIn('affected_person_id', $ap())
                    ->count();
            case 'land':
                return DB::table('land')
                    ->whereIn('affected_person_id', $ap())
                    ->count();
            case 'crop':
                return DB::table('crop')
                    ->whereIn('land_id', $land())
                    ->count();
            case 'structure':
                return DB::table('infrastructure')
                    ->whereIn('affected_person_id', $ap())
                    ->count();
            case 'tree':
                return DB::table('tree')
                    ->whereIn('affected_person_id', $ap())
                    ->count();
            case 'tenant':
                return DB::table('tenant')
                    ->whereIn('affected_person_id', $ap())
                    ->count();
            case 'business':
                return DB::table('business')
                    ->whereIn('affected_person_id', $ap())
                    ->count();
            case 'worker':
                return DB::table('worker')
                    ->whereIn('affected_person_id', $ap())
                    ->count();
            case 'gps':
                return DB::table('affected_person')
                    ->where('project_id', $projectId)
                    ->where('status', 'DRAFT')
                    ->whereNotNull('gps_latitude')
                    ->count();
            default:
                return 0;
        }
    }

    /**
     * Delete all DRAFT rows for one import step, respecting FK order.
     *
     * Tables are removed deepest-first so that RESTRICT foreign keys never
     * block the deletion. Each subquery closure creates a fresh query builder
     * so they can be reused across whereIn calls safely.
     *
     * @return int Number of rows deleted.
     */
    private function clearStepData(string $step, int $projectId): int
    {
        $total = 0;

        $ap = fn () => DB::table('affected_person')
            ->where('project_id', $projectId)
            ->where('status', 'DRAFT')
            ->select('affected_person_id');

        $land = fn () => DB::table('land')
            ->whereIn('affected_person_id', $ap())
            ->select('land_id');

        $crop = fn () => DB::table('crop')
            ->whereIn('land_id', $land())
            ->select('crop_id');

        $infra = fn () => DB::table('infrastructure')
            ->whereIn('affected_person_id', $ap())
            ->select('infrastructure_id');

        $tree = fn () => DB::table('tree')
            ->whereIn('affected_person_id', $ap())
            ->select('tree_id');

        $tenant = fn () => DB::table('tenant')
            ->whereIn('affected_person_id', $ap())
            ->select('tenant_id');

        $biz = fn () => DB::table('business')
            ->whereIn('affected_person_id', $ap())
            ->select('business_id');

        $tenantBiz = fn () => DB::table('business')
            ->whereIn('tenant_id', $tenant())
            ->select('business_id');

        $worker = fn () => DB::table('worker')
            ->whereIn('affected_person_id', $ap())
            ->select('worker_id');

        $del = function (string $table, string $column, $sub) use (&$total): void {
            $total += DB::table($table)->whereIn($column, $sub())->delete();
        };

        switch ($step) {
            // EP (step 1) — full graph, deepest-first
            case 'ep':
                $del('crop_assessment', 'crop_id', $crop);
                $del('crop', 'land_id', $land);
                $del('land_assessment', 'land_id', $land);
                $del('tree_assessment', 'tree_id', $tree);
                $del('infrastructure_assessment', 'infrastructure_id', $infra);
                $del('worker_assessment', 'worker_id', $worker);
                $del('business_loss', 'business_id', $tenantBiz);
                $del('worker', 'business_id', $tenantBiz);
                $del('business', 'tenant_id', $tenant);
                $del('business_loss', 'business_id', $biz);
                $del('worker', 'affected_person_id', $ap);
                $del('business', 'affected_person_id', $ap);
                $del('tenant', 'affected_person_id', $ap);
                $del('family_member', 'affected_person_id', $ap);
                $del('infrastructure', 'affected_person_id', $ap);
                $del('land', 'affected_person_id', $ap);
                $del('tree', 'affected_person_id', $ap);
                $del('affected_person', 'affected_person_id', $ap);
                break;

            // ── Family (step 2) ──────────────────────────────────────
            case 'family':
                $del('family_member', 'affected_person_id', $ap);
                break;

            // ── Land (step 3) — must clear crops first ───────────────
            case 'land':
                $del('crop_assessment', 'crop_id', $crop);
                $del('crop', 'land_id', $land);
                $del('land_assessment', 'land_id', $land);
                $del('land', 'affected_person_id', $ap);
                break;

            // ── Crop (step 4) ────────────────────────────────────────
            case 'crop':
                $del('crop_assessment', 'crop_id', $crop);
                $del('crop', 'land_id', $land);
                break;

            // ── Structure (step 5) ───────────────────────────────────
            case 'structure':
                $del('infrastructure_assessment', 'infrastructure_id', $infra);
                $del('infrastructure', 'affected_person_id', $ap);
                break;

            // ── Tree (step 6) ────────────────────────────────────────
            case 'tree':
                $del('tree_assessment', 'tree_id', $tree);
                $del('tree', 'affected_person_id', $ap);
                break;

            // ── Tenant (step 7) — businesses reference tenants ──────
            case 'tenant':
                $del('worker', 'business_id', $tenantBiz);
                $del('business_loss', 'business_id', $tenantBiz);
                $del('business', 'tenant_id', $tenant);
                $del('tenant', 'affected_person_id', $ap);
                break;

            // ── Business (step 8) — workers reference businesses ────
            case 'business':
                $del('worker', 'business_id', $biz);
                $del('business_loss', 'business_id', $biz);
                $del('business', 'affected_person_id', $ap);
                break;

            // ── Worker (step 9) ──────────────────────────────────────
            case 'worker':
                $del('worker_assessment', 'worker_id', $worker);
                $del('worker', 'affected_person_id', $ap);
                break;

            // ── GPS (step 10) — clear coordinates on DRAFT EPs ──────
            case 'gps':
                return DB::table('affected_person')
                    ->where('project_id', $projectId)
                    ->where('status', 'DRAFT')
                    ->update([
                        'gps_latitude' => null,
                        'gps_longitude' => null,
                    ]);

            default:
                return 0;
        }

        return $total;
    }
